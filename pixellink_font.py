GLYPH_WIDTH  = 3
GLYPH_HEIGHT = 5


def get_glyph(char):
    '''Returns a 5x3 (row-major) bitmap for char, or None if not in the font.'''
    if char in LETTERS:
        return LETTERS[char]
    lower = char.lower()
    if lower in LETTERS:
        return LETTERS[lower]
    if char in NUMBERS:
        return NUMBERS[char]
    if char in SYMBOLS:
        return SYMBOLS[char]
    return None
